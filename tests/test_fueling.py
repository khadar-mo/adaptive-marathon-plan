def report(**changes):
    return {"kind": "fueling", "source": "self-report", "source_id": "synthetic-fueling",
            "activity_id": 1, "actor": "Synthetic runner", "reported_at": "2026-10-25T14:00:00+00:00",
            "practice_status": "COMPLETED", **changes}


async def enter(client, payload, status=200, activity_id=1):
    response = await client.post(f"/api/activities/{activity_id}/fueling", content=context.encoded(payload), headers={"Content-Type": "application/json"})
    assert response.status_code == status, response.text
    return response.json()


async def read(client, activity_id=1, **params):
    response = await client.get(f"/api/activities/{activity_id}/fueling", params=params)
    assert response.status_code == 200, response.text
    return response.json()


async def test_optional_unknown_and_verbatim_entry_leave_activity_and_efforts_unchanged(history, tmp_path, monkeypatch):
    raw = trace_fit()
    strategy = '  My note: 60.12345678901234567890 g/h, water at 00:30.\nNo generated dose. <script>alert(1)</script>  '
    async with server() as client:
        await upload(client, ("made-up.fit", raw))
        capture_time=context.now()
        monkeypatch.setattr(canonical,'knowledge_time',lambda:capture_time)
        before = {path: (await client.get(path)).json() for path in (
            "/api/activities/1", "/api/activities/1/canonical", "/api/activities/1/efforts",
            "/api/estimators?cutoff=2026-10-26T00:00:00Z")}
        missing = await read(client)
        assert missing["state"] == "MISSING" and missing["reports"] == []
        assert missing["practice_status"] == missing["tolerance_status"] == "UNKNOWN"
        assert missing["research_status"] == "RESEARCH_PENDING"
        assert 'Record fueling practice and tolerance' in (await client.get('/activities/1')).text
        assert '/activities/1/workout' in (await client.get('/activities/1')).text
        payload = report(user_strategy=strategy, notes="  literal\nnotes ♥  ")
        saved = await enter(client, payload)
        row, = (await read(client))["reports"]
        assert row["user_strategy"] == strategy and row["notes"] == payload["notes"]
        assert row["tolerance"] is None and row["tolerance_status"] == "UNKNOWN"
        assert row["practice_status"] == "COMPLETED" and row["research_status"] == "RESEARCH_PENDING"
        assert row["target_at_entry"]["canonical_version_id"] == before["/api/activities/1/canonical"]["version_id"]
        assert any(s["sha256"] == hashlib.sha256(raw).hexdigest() for s in row["target_at_entry"]["sources"])
        exact = (await client.get('/api/fueling/versions/'+row['version_id'])).json()
        assert exact == row
        archive = tmp_path/'archive'/saved['raw_sha256']
        assert archive.read_bytes() == context.encoded(payload).encode()
        assert (await enter(client, payload))["replayed"]
        assert len((await read(client))["reports"]) == 1
        for path, original in before.items():
            assert (await client.get(path)).json() == original
        html = (await client.get('/activities/1/fueling')).text
        assert '&lt;script&gt;alert(1)&lt;/script&gt;' in html and '<script>alert(1)</script>' not in html


async def test_existing_g2_database_preserves_independent_distance_and_saved_efforts(history, tmp_path):
    fixture = json.loads(gzip.decompress((Path(__file__).parent/'fixtures'/'workout-g2-59faa54.json.gz').read_bytes()))
    with sqlite3.connect(tmp_path/'runs.sqlite3') as db:
        db.executescript(fixture['sql'])
    Archive(tmp_path/'archive').put(bytes.fromhex(fixture['raw_hex']))
    async with server() as client:
        # The pre-existing fixture was generated by merged 59faa54: 30 m in 6 s.
        before = (await client.get('/api/activities/1')).json()
        efforts_before = (await client.get('/api/activities/1/efforts')).json()
        assert before['distance_m'] == 30 and before['elapsed_seconds'] == 6
        assert efforts_before['version_id'] == fixture['version_id']
        assert (await read(client))['tolerance_status'] == 'UNKNOWN'
        saved = await enter(client, report(user_strategy='Keep my existing strategy exactly.', tolerance='Felt comfortable', tolerance_reported_at='2026-10-25T13:00:00Z'))
        assert saved['records'][0]['revision'] == 1
        assert (await client.get('/api/activities/1')).json() == before
        assert (await client.get('/api/activities/1/efforts')).json() == efforts_before
        await upload(client, ('existing-format.fit', bytes.fromhex(fixture['raw_hex'])))
        assert len((await read(client))['reports']) == 1
        assert (await client.get('/api/activities/1/efforts')).json()['version_id'] == fixture['version_id']


async def test_genuine_g0_store_missing_canonical_tables_read_entry_correction_replay(history, tmp_path):
    fixture=json.loads(gzip.decompress((Path(__file__).parent/'fixtures'/'fueling-g0-4a0630f.json.gz').read_bytes()))
    assert fixture['base_commit']=='4a0630f65885b1515e59302075e37c5632bcb2da'
    path=tmp_path/'runs.sqlite3'
    with sqlite3.connect(path) as db:
        db.executescript(fixture['sql'])
        assert not db.execute("SELECT 1 FROM sqlite_master WHERE name='canonical_activity_heads'").fetchone()
    archive=Archive(tmp_path/'archive')
    archive.put(bytes.fromhex(fixture['raw_hex']))
    async with server() as client:
        before=(await client.get('/api/activities/1')).json()
        assert before['distance_m']==10000 and before['elapsed_seconds']==3600
        old_bytes=path.read_bytes()
        absent=await read(client)
        assert absent['state']=='MISSING' and absent['practice_status']==absent['tolerance_status']=='UNKNOWN'
        assert absent['target_now']['canonical_version_id'] is None
        assert (await client.get('/activities/1/fueling')).status_code==200
        assert path.read_bytes()==old_bytes  # inspection neither upgrades nor repairs old data
        first=(await enter(client,report(user_strategy='  old source note  ')))['records'][0]
        initial=(await client.get('/api/fueling/versions/'+first['version_id'])).json()
        assert initial['target_at_entry']['canonical_version_id'] is None
        assert any(s['sha256']==fixture['source_sha256'] for s in initial['target_at_entry']['sources'])
        second=await enter(client,report(notes='Corrected on legacy source',supersedes=first['version_id'],correction_reason='Added a note'))
        assert second['records'][0]['revision']==2
        assert (await enter(client,report(user_strategy='  old source note  ')))['replayed']
        assert (await read(client))['reports'][0]['version_id']==second['records'][0]['version_id']
        assert (await client.get('/api/fueling/versions/'+first['version_id'])).json()==initial
        assert (await client.get('/api/activities/1')).json()==before
    async with server() as client:
        assert (await read(client))['reports'][0]['version_id']==second['records'][0]['version_id']
        assert (await client.get('/api/activities/1')).json()==before


